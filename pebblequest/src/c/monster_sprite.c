uint64_t get_monster_sprite(const char *name) {
    if (!name) return 0;
    for (int i = 0; monster_sprites[i].name; i++) {
        if (strcmp(monster_sprites[i].name, name) == 0) {
            return monster_sprites[i].sprite;
        }
    }
    return 0;
}
